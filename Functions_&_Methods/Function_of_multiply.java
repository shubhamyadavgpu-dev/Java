public class Function_of_multiply {
    public static int Multiply (int m, int n){
        int mul = m * n ;
        return mul;
    }
    public static void main(String args[]){
        int a = 5 ;
        int b = 8 ;
        System.out.println("Multiply = "+Multiply(a,b));
        System.out.println("Multiply = "+Multiply(10,23));
    }
}